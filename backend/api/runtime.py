def _cors_origins():
    """Return only explicitly configured browser origins in production."""
    configured = [
        origin.strip().rstrip("/")
        for origin in os.getenv("CORS_ORIGINS", "").split(",")
        if origin.strip()
    ]
    if IS_PRODUCTION and "*" in configured:
        raise RuntimeError("CORS_ORIGINS ne peut pas contenir '*' en production.")
    local_origins = [
        "http://localhost:3000",
        "http://127.0.0.1:3000",
        "http://localhost:3001",
        "http://127.0.0.1:3001",
    ]
    if IS_PRODUCTION:
        return list(dict.fromkeys(configured))
    return list(dict.fromkeys(configured + local_origins))

