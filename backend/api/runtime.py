@app.middleware("http")
async def request_observability(request: Request, call_next):
    """Attach a correlation id and emit one safe, structured access event."""
    request_id = request_id_from_header(request.headers.get("X-Request-ID"))
    request.state.request_id = request_id
    context_token = set_request_id(request_id)
    started_at = time.perf_counter()
    client_ip = request.client.host if request.client else ""
    try:
        response = await call_next(request)
    except Exception:
        duration_ms = round((time.perf_counter() - started_at) * 1000, 2)
        metrics.record(500, duration_ms / 1000)
        logger.exception(
            "HTTP request failed",
            extra={
                "event": "http_access",
                "method": request.method,
                "path": request.url.path,
                "status_code": 500,
                "duration_ms": duration_ms,
                "client_ip": client_ip,
                "username": getattr(request.state, "access_username", ""),
                "role": getattr(request.state, "access_role", ""),
            },
        )
        raise
    else:
        duration_ms = round((time.perf_counter() - started_at) * 1000, 2)
        metrics.record(response.status_code, duration_ms / 1000)
        response.headers["X-Request-ID"] = request_id
        logger.info(
            "HTTP request completed",
            extra={
                "event": "http_access",
                "method": request.method,
                "path": request.url.path,
                "status_code": response.status_code,
                "duration_ms": duration_ms,
                "client_ip": client_ip,
                "username": getattr(request.state, "access_username", ""),
                "role": getattr(request.state, "access_role", ""),
            },
        )
        return response
    finally:
        reset_request_id(context_token)


@app.middleware("http")
async def savia_language_context(request: Request, call_next):
    token = _LANG_CONTEXT.set(_get_app_language(request.headers.get("x-savia-lang")))
    try:
        return await call_next(request)
    finally:
        _LANG_CONTEXT.reset(token)


@app.middleware("http")
async def security_response_headers(request: Request, call_next):
    response = await call_next(request)
    response.headers["X-Content-Type-Options"] = "nosniff"
    response.headers["X-Frame-Options"] = "DENY"
    response.headers["Referrer-Policy"] = "same-origin"
    response.headers["Permissions-Policy"] = "camera=(self), geolocation=(), microphone=()"
    response.headers["Content-Security-Policy"] = "default-src 'none'; base-uri 'none'; frame-ancestors 'none'; form-action 'none'"
    response.headers["Cross-Origin-Opener-Policy"] = "same-origin"
    response.headers["Cross-Origin-Resource-Policy"] = "same-origin"
    response.headers["X-Permitted-Cross-Domain-Policies"] = "none"
    if IS_PRODUCTION:
        response.headers["Strict-Transport-Security"] = "max-age=31536000; includeSubDomains"
    return response


@app.exception_handler(Exception)
async def unhandled_exception_handler(request: Request, exc: Exception):
    """Return a CORS-compatible JSON error instead of an opaque browser failure."""
    logger.exception("Unhandled API error on %s %s", request.method, request.url.path)
    return JSONResponse(
        status_code=500,
        content={"error": "Erreur interne du serveur", "request_id": current_request_id()},
    )

